package proyecto;

/**
 * Enumeración que define las acciones posibles en el sistema.
 * 
 * Esta enumeración representa los diferentes tipos de acciones que pueden
 * ser registradas en el sistema de logs, como compras, ventas, inicio y fin
 * de partidas, y registros del sistema.
 * 
 * @author Pablo Manuel y Cristian
 * @version 2.0
 */
public enum Accion {
	REGISTRO,
    COMPRA_CARTA,
    VENTA_CARTA,
}

package proyecto;

/**
 * Enumeración que define los niveles de rareza de las cartas.
 * 
 * Esta enumeración representa las diferentes categorías de rareza
 * que pueden tener las cartas en el sistema, desde la más común
 * hasta la más legendaria.
 * 
 * @author Pablo Manuel y Cristian
 * @version 2.0
 */
public enum Rareza {
    /** Carta de rareza común, la más frecuente. */
    Comun,
    /** Carta de rareza rara, menos común. */
    Rara,
    /** Carta de rareza épica, bastante rara. */
    Epica,
    /** Carta de rareza legendaria, la más rara y valiosa. */
    Legendaria
}